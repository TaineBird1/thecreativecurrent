/**
 * Creates a stand-in for convex/_generated so `tsc` can run before anyone has
 * connected to a Convex deployment.
 *
 * Why this exists: the real convex/_generated only appears after
 * `npx convex dev` has talked to a live deployment, which needs a browser
 * login. Without it, `tsc --noEmit` cannot resolve a single import and reports
 * nothing useful — so type errors sat undetected until the first deploy, which
 * is precisely where they turned up.
 *
 * What it does and does not buy you:
 *   - Doc, Id, TableNames and the ctx types are derived from the REAL schema
 *     via Convex's own public helper types, so schema and ctx.db mistakes are
 *     caught properly.
 *   - `api` and `internal` are typed loosely. Function references are checked
 *     separately and more precisely by scripts/check-convex-refs.mjs.
 *
 * It refuses to touch a real _generated directory. Run `npx convex dev` and the
 * genuine article replaces this entirely.
 */
import { existsSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "convex", "_generated");
const marker = join(dir, ".stub");

if (existsSync(dir) && !existsSync(marker)) {
  console.log("convex/_generated is the real thing — leaving it alone.");
  process.exit(0);
}

mkdirSync(dir, { recursive: true });
writeFileSync(marker, "Generated by scripts/stub-generated.mjs. Safe to delete.\n");

writeFileSync(
  join(dir, "dataModel.d.ts"),
  `// STUB — see scripts/stub-generated.mjs. Replaced by \`npx convex dev\`.
import type {
  DataModelFromSchemaDefinition,
  DocumentByName,
  TableNamesInDataModel,
  GenericDatabaseReader,
  GenericDatabaseWriter,
} from "convex/server";
import type { GenericId } from "convex/values";
import schema from "../schema";

export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
export type TableNames = TableNamesInDataModel<DataModel>;
export type Doc<T extends TableNames> = DocumentByName<DataModel, T>;
export type Id<T extends TableNames> = GenericId<T>;
export type DatabaseReader = GenericDatabaseReader<DataModel>;
export type DatabaseWriter = GenericDatabaseWriter<DataModel>;
`,
);

writeFileSync(
  join(dir, "server.d.ts"),
  `// STUB — see scripts/stub-generated.mjs. Replaced by \`npx convex dev\`.
import type {
  GenericActionCtx,
  GenericMutationCtx,
  GenericQueryCtx,
} from "convex/server";
import type { DataModel } from "./dataModel";

export declare const query: import("convex/server").QueryBuilder<DataModel, "public">;
export declare const internalQuery: import("convex/server").QueryBuilder<DataModel, "internal">;
export declare const mutation: import("convex/server").MutationBuilder<DataModel, "public">;
export declare const internalMutation: import("convex/server").MutationBuilder<DataModel, "internal">;
export declare const action: import("convex/server").ActionBuilder<DataModel, "public">;
export declare const internalAction: import("convex/server").ActionBuilder<DataModel, "internal">;
export declare const httpAction: import("convex/server").HttpActionBuilder;

export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
export type ActionCtx = GenericActionCtx<DataModel>;
`,
);

writeFileSync(
  join(dir, "api.d.ts"),
  `// STUB — see scripts/stub-generated.mjs. Replaced by \`npx convex dev\`.
//
// The real file is a precisely typed tree of every function. Reproducing that
// without a deployment isn't possible, so these are loose here and
// scripts/check-convex-refs.mjs checks references instead — it verifies every
// api.*/internal.* path resolves to a real export with the right visibility,
// which is the part that actually goes wrong.
/* eslint-disable @typescript-eslint/no-explicit-any */
export declare const api: any;
export declare const internal: any;
`,
);

for (const [file, body] of [
  ["api.js", `export const api = new Proxy({}, { get: () => api });\nexport const internal = api;\n`],
  ["server.js", `export const query = (f) => f;\nexport const internalQuery = (f) => f;\nexport const mutation = (f) => f;\nexport const internalMutation = (f) => f;\nexport const action = (f) => f;\nexport const internalAction = (f) => f;\nexport const httpAction = (f) => f;\n`],
]) {
  writeFileSync(join(dir, file), body);
}

console.log("Stubbed convex/_generated — `pnpm typecheck` can now run. `npx convex dev` replaces it.");
